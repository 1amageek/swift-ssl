  func testPrivateKeyValidationAndBoundedGenerationFailure() {
    let zero = ContiguousArray<UInt8>(repeating: 0, count: P256PrivateKey.byteCount)
    do {
      let unexpected = try P256PrivateKey(bytes: zero.span)
      _ = consume unexpected
      XCTFail("P-256 accepted the zero private scalar")
    } catch {
      XCTAssertEqual(error as? CryptoInputError, .nonCanonicalEncoding)
    }

    let order = bytes(
      "FFFFFFFF00000000FFFFFFFFFFFFFFFFBCE6FAADA7179E84F3B9CAC2FC632551"
    )
    do {
      let unexpected = try P256PrivateKey(bytes: order.span)
      _ = consume unexpected
      XCTFail("P-256 accepted its group order as a private scalar")
    } catch {
      XCTAssertEqual(error as? CryptoInputError, .nonCanonicalEncoding)
    }

    let entropy = FixedEntropy(bytes: zero)
    do {
      let unexpected = try P256PrivateKey.generate(using: entropy)
      _ = consume unexpected
      XCTFail("P-256 generation accepted 256 invalid candidates")
    } catch {
      XCTAssertEqual(error as? P256KeyGenerationError, .invalidScalar)
    }
  }

  private func bytes(_ value: String) -> ContiguousArray<UInt8> {
    var result = ContiguousArray<UInt8>()
    result.reserveCapacity(value.count / 2)
    var index = value.startIndex
    while index < value.endIndex {
      let next = value.index(index, offsetBy: 2)
      result.append(UInt8(value[index..<next], radix: 16)!)
      index = next
    }
    return result
  }

  private func copy(_ value: Span<UInt8>) -> [UInt8] {
    var result: [UInt8] = []
    result.reserveCapacity(value.count)
    var index = 0
    while index < value.count {
      result.append(value[index])
      index += 1
    }
    return result
  }

  private struct FixedEntropy: EntropySource {
    let bytes: ContiguousArray<UInt8>

    func fill(_ destination: inout MutableSpan<UInt8>) throws(EntropyError) {
      guard destination.count == bytes.count else {
        throw .partialFill(expected: destination.count, actual: bytes.count)
      }
      var index = 0
      while index < bytes.count {
        destination[index] = bytes[index]
        index += 1
      }
    }
  }
